//Criando um Bubble Sort em JavaScript e também criando uma busca binária para encontrar um elemento no array ordenado
//Para um conjunto de dados não ordenados só existe a busca linear, que percorre o array do início ao fim, 
// verificando cada elemento até encontrar o desejado. No entanto, quando os dados estão ordenados, podemos utilizar a busca binária, 
// que é muito mais eficiente.
//A busca binária funciona da seguinte forma: ela começa verificando o elemento do meio do array. 
//Se o elemento que estamos procurando for menor do que o elemento do meio, então ele só pode estar na metade inferior do array. 
//Se for maior, então ele só pode estar na metade superior. Esse processo é repetido até que o elemento seja encontrado ou até 
//que a sublista seja reduzida a zero.
//Não existe uma posição negativa em um array, então se o elemento não for encontrado, a função retorna -1.
//Se você for usar esporeticamente a busca linear é melhor, agora se você for fazer uma busca diariamente é melhor usar a busca binária, 
// pois ela é muito mais eficiente.


